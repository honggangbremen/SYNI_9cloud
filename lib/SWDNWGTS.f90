   inital_wgt18 = .false.

end subroutine   set_up_swdnwgts
!===========================================================================================
subroutine get_swdnwgts 
integer ib

if ( inital_wgt18 ) call set_up_swdnwgts


wgt18%wgt(1:4) = 0.000

do ib = 5,nband 
  swdwt%val(1) = float(ib)
  swdwt%val(2) = wgt18%lnpw
  swdwt%val(3) = float(wgt18%isid)
  swdwt%val(4) = wgt18%u0
  swdwt%val(5) = wgt18%lnctau

  CALL lut_guts(swdwt)

 wgt18%wgt(ib)= swdwt%RESULT
 
enddo

end subroutine get_swdnwgts

END MODULE SWDNWGTS

